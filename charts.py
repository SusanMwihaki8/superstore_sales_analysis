import pandas as pd 
import matplotlib.pyplot as plt 
data=pd.read_excel("superstore.xls")
region_sales=data.groupby("Region")["Sales"].sum()
data["YearMonth"]=data["Order Date"].dt.to_period("M")
monthly_sales=data.groupby("YearMonth")["Sales"].sum()
category_profit=data.groupby("Category")["Profit"].sum()
fig, axes=plt.subplots(2,2,figsize=(12,8))
bars=axes[0,0].bar(region_sales.index, region_sales.values)
axes[0,0].set_title("Sales by Region")
axes[0,0].set_xlabel("Region")
axes[0,0].set_ylabel("Sales")
axes[0,0].bar_label(bars, fmt="%.0f")#adds sales values above each bar 
axes[0,1].plot(monthly_sales.index.to_timestamp(),monthly_sales.values,marker="D",linewidth=1)
axes[0,1].set_title("Monthly sales trend")
axes[0,1].set_xlabel("Months")
axes[0,1].set_ylabel("Sales")
axes[0,1].tick_params(axis="x",rotation=45)
axes[0,1].grid(True)
axes[0,1].legend(["Monthly sales"])
axes[1,0].pie(category_profit.values,labels=category_profit.index,autopct="%1.1f%%",startangle=90)
axes[1,0].set_title("Total profit by category")
axes[1,1].scatter(data["Sales"],data["Profit"],alpha=0.5)
axes[1,1].set_title("Sales vs Profit")
axes[1,1].set_xlabel("Sales")
axes[1,1].set_ylabel("Profit")
axes[1,1].axhline(y=0,linestyle="--")
plt.tight_layout()
plt.savefig("charts.png")
plt.show()